export function getDistinctIngredientVisual(
  id: string,
  name?: string,
  aisle?: string,
): IngredientVisual {
  const normId = id.toLowerCase().trim();
  if (DISTINCT_INGREDIENT_ICONS[normId]) {
    return DISTINCT_INGREDIENT_ICONS[normId];
  }

  // Singularize common plural suffixes
  const singular = normId.endsWith('s') ? normId.slice(0, -1) : normId;
  if (DISTINCT_INGREDIENT_ICONS[singular]) {
    return DISTINCT_INGREDIENT_ICONS[singular];
  }

  // Check ingredient name keywords
  const lowerName = (name ?? '').toLowerCase();
  for (const [key, visual] of Object.entries(DISTINCT_INGREDIENT_ICONS)) {
    if (lowerName.includes(key) || key.includes(normId)) {
      return visual;
    }
  }

  const aisleKey = (aisle ?? 'other').toLowerCase();
  return AISLE_ICONS[aisleKey] ?? AISLE_ICONS.other;
}
